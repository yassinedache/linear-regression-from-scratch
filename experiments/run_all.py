md = ["# Results", "", "Generated by `python experiments/run_all.py`.", ""]
tex = ["% Generated by experiments/run_all.py: do not edit by hand.", ""]


def macro(name, value):
    tex.append("\\newcommand{\\%s}{%s}" % (name, value))


def save(fig, name):
    fig.tight_layout()
    for ext in ("png", "pdf"):
        fig.savefig(os.path.join(FIG, f"{name}.{ext}"))
    plt.close(fig)
    print("saved figures/%s.png/.pdf" % name)


def sci(x, digits=1):
    """1.2e-07 -> 1,2 \\times 10^{-7} for LaTeX (French decimal comma)."""
    m, e = f"{x:.{digits}e}".split("e")
    return f"{m.replace('.', '{,}')} \\times 10^{{{int(e)}}}"


def fr(x, digits=4):
    return f"{x:.{digits}f}".replace(".", "{,}")


# --------------------------------------------------------------------------- data
X, y, names = data.load_california()
Xtr, Xte, ytr, yte = data.train_test_split(X, y, test_size=0.2, seed=42)
scaler = data.Standardizer().fit(Xtr)
A_tr, A_te = ls.add_intercept(scaler.transform(Xtr)), ls.add_intercept(scaler.transform(Xte))
macro("nRows", f"{len(y):,}".replace(",", "\\,"))
macro("nTrain", f"{len(ytr):,}".replace(",", "\\,"))
macro("nTest", f"{len(yte):,}".replace(",", "\\,"))


# ------------------------------------------------------- 1. fits and scikit-learn
def experiment_fits():
    from sklearn.linear_model import LinearRegression

    results = {}
    t = time.perf_counter(); w_ne = ls.fit_normal_equations(A_tr, ytr); results["Normal equations (Cholesky)"] = (w_ne, time.perf_counter() - t)
    t = time.perf_counter(); w_qr = ls.fit_qr(A_tr, ytr); results["QR (Householder)"] = (w_qr, time.perf_counter() - t)
    t = time.perf_counter(); g = gd.gradient_descent(A_tr, ytr, "optimal", n_iter=20000, tol=1e-10); results["Gradient descent"] = (g.w, time.perf_counter() - t)
    t = time.perf_counter(); sk = LinearRegression().fit(scaler.transform(Xtr), ytr); t_sk = time.perf_counter() - t
    w_sk = np.concatenate([[sk.intercept_], sk.coef_])
    results["scikit-learn LinearRegression"] = (w_sk, t_sk)

    md.extend(["## 1. California Housing: comparison with scikit-learn", "",
               f"{len(y)} block groups, {len(ytr)} for training and {len(yte)} for testing. Target in units of 100,000 $.", "",
               "| Method | Test RMSE ($) | Test MAE ($) | Test R2 | max abs(w - w_sklearn) | Time (ms) |", "|---|---|---|---|---|---|"])
    rows_tex = []
    keys = {"Normal equations (Cholesky)": "NE", "QR (Householder)": "QR", "Gradient descent": "GD", "scikit-learn LinearRegression": "SK"}
    labels_fr = {"NE": "\\'Equations normales (Cholesky)", "QR": "QR (Householder)", "GD": "Descente de gradient", "SK": "scikit-learn"}
    for name, (w, dt) in results.items():
        p = A_te @ w
        rm, ma, r2 = metrics.rmse(yte, p) * 1e5, metrics.mae(yte, p) * 1e5, metrics.r2(yte, p)
        diff = float(np.max(np.abs(w - w_sk)))
        md.append(f"| {name} | {rm:,.0f} | {ma:,.0f} | {r2:.4f} | {diff:.1e} | {dt * 1000:.1f} |")
        k = keys[name]
        diff_tex = "--" if k == "SK" else f"${sci(diff)}$"
        rows_tex.append(f"{labels_fr[k]} & {rm:,.0f} & {ma:,.0f} & {fr(r2)} & {diff_tex} \\\\".replace(",", "\\,").replace("{\\,}", "{,}"))
        macro(f"rTwo{k}", fr(r2))
        macro(f"rmse{k}", f"{rm:,.0f}".replace(",", "\\,"))
    macro("gdIters", str(g.iterations))
    tex.append("\\newcommand{\\tableMethods}{%")
    tex.extend(rows_tex)
    tex.append("}")

    md.extend(["", f"Gradient descent with the optimal fixed step converged in {g.iterations} iterations (gradient norm < 1e-10).", "",
               "Standardised coefficients (QR):", "", "| Feature | Coefficient | scikit-learn |", "|---|---|---|"])
    coef_tex = []
    for i, n in enumerate(["Intercept"] + names):
        md.append(f"| {n} | {w_qr[i]:+.4f} | {w_sk[i]:+.4f} |")
        coef_tex.append(f"\\texttt{{{n}}} & ${w_qr[i]:+.4f}$ & ${w_sk[i]:+.4f}$ \\\\".replace(".", "{,}"))
    tex.append("\\newcommand{\\tableCoefs}{%")
    tex.extend(coef_tex)
    tex.append("}")
    md.append("")

    # predictions figure
    p = A_te @ w_qr
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(10, 4))
    ax1.scatter(yte, p, s=3, alpha=0.25, color=PURPLE)
    lim = [min(yte.min(), p.min()), max(yte.max(), p.max())]
    ax1.plot(lim, lim, color=ORANGE, lw=1.5, label="perfect prediction")
    ax1.set_xlabel("true value (100,000 $)")
    ax1.set_ylabel("predicted value (100,000 $)")
    ax1.set_title(f"Test set: R2 = {metrics.r2(yte, p):.3f}")
    ax1.legend()
    ax2.hist(yte - p, bins=80, color=PURPLE, alpha=0.8)
    ax2.set_xlabel("residual y - prediction (100,000 $)")
    ax2.set_title("Residuals (capped prices at 5 create the right tail)")
    save(fig, "1_predictions")
    return w_qr


# ------------------------------------------------------------- 2. step size study
def experiment_steps():
    mu, L = gd.hessian_spectrum(A_tr)
    kappa = L / mu
    w_star = ls.fit_qr(A_tr, ytr)
    f_star = gd.loss(w_star, A_tr, ytr)
    steps = [("0.1 / L", 0.1 / L), ("1 / L", 1 / L), ("2 / (L + mu) optimal", 2 / (L + mu)), ("1.9 / L", 1.9 / L), ("2.05 / L", 2.05 / L)]
    colors = [GREY, PURPLE, ORANGE, DARK, "#D64545"]
    fig, ax = plt.subplots(figsize=(7, 4.2))
    md.extend(["## 2. Gradient descent: choice of the step", "",
               f"Hessian H = (2/n) X^T X on standardised data: mu = {mu:.4f}, L = {L:.4f}, condition number kappa = {kappa:.1f}.", "",
               "| Step | Theoretical rate rho | Observed rate | Iterations to f - f* < 1e-10 |", "|---|---|---|---|"])
    rows_tex = []
    for (label, eta), c in zip(steps, colors):
        res = gd.gradient_descent(A_tr, ytr, eta, n_iter=600, tol=0)
        gap = np.maximum(np.array(res.losses) - f_star, 1e-300)
        rho_th = max(abs(1 - eta * mu), abs(1 - eta * L))
        k = np.arange(len(gap))
        sel = (gap > 1e-13) & (k > 50) & np.isfinite(gap)
        rho_obs = float(np.exp(np.polyfit(k[sel], np.log(gap[sel]), 1)[0] / 2)) if sel.sum() > 5 else float("nan")
        reach = np.nonzero(gap < 1e-10)[0]
        it = str(int(reach[0])) if reach.size else ("diverges" if rho_th > 1 else "> 600")
        ax.semilogy(k, np.minimum(gap, 1e6), color=c, lw=1.6, label=f"eta = {label} (rho = {rho_th:.3f})")
        md.append(f"| {label} | {rho_th:.4f} | {rho_obs:.4f} | {it} |")
        it_tex = "diverge" if it == "diverges" else ("$> 600$" if it.startswith(">") else it)
        lab = label.replace(" optimal", "").replace("mu", "\\mu").replace(".", "{,}")
        rows_tex.append(f"${lab}$ & {fr(rho_th)} & {fr(rho_obs) if np.isfinite(rho_obs) else '--'} & {it_tex} \\\\")
    ax.set_ylim(1e-14, 1e6)
    ax.set_xlabel("iteration k")
    ax.set_ylabel("f(w_k) - f*")
    ax.set_title(f"Gradient descent on California Housing (kappa = {kappa:.1f})")
    ax.legend(fontsize=8)
    save(fig, "2_step_sizes")
    md.extend(["", "Theory: with H's eigenvalues in [mu, L], the error is multiplied by at most rho = max(|1 - eta mu|, |1 - eta L|) per step, so f - f* decays like rho^(2k). It converges iff eta < 2/L; the optimal fixed step gives rho = (kappa - 1)/(kappa + 1).", ""])
    macro("muH", fr(mu))
    macro("LH", fr(L))
    macro("kappaH", f"{kappa:.1f}".replace(".", "{,}"))
    macro("rhoOpt", fr((kappa - 1) / (kappa + 1)))
    tex.append("\\newcommand{\\tableSteps}{%")
    tex.extend(rows_tex)
    tex.append("}")


# ---------------------------------------------------------- 3. effect of scaling
def experiment_scaling():
    md.extend(["## 3. Effect of standardising the features", "", "Gradient descent with the optimal fixed step, 2000 iterations:", ""])
    A_raw = ls.add_intercept(Xtr)
    mu_r, L_r = gd.hessian_spectrum(A_raw)
    mu_s, L_s = gd.hessian_spectrum(A_tr)
    fig, ax = plt.subplots(figsize=(7, 4.2))
    for A, c, label in ((A_raw, GREY, f"raw features (kappa = {L_r / mu_r:.1e})"), (A_tr, ORANGE, f"standardised (kappa = {L_s / mu_s:.1f})")):
        w_star = ls.fit_qr(A, ytr)
        f_star = gd.loss(w_star, A, ytr)
        res = gd.gradient_descent(A, ytr, "optimal", n_iter=2000, tol=0)
        gap = np.maximum((np.array(res.losses) - f_star) / (res.losses[0] - f_star), 1e-17)
        ax.semilogy(gap, color=c, lw=1.6, label=label)
        md_label = "raw" if A is A_raw else "standardised"
        md.append(f"- {md_label}: kappa = {L_r / mu_r if A is A_raw else L_s / mu_s:.3g}, relative gap after 2000 iterations = {gap[-1]:.2e}")
        macro("gapRaw" if A is A_raw else "gapStd", "< 10^{-15}" if gap[-1] < 1e-15 else sci(gap[-1]))
    ax.set_xlabel("iteration k")
    ax.set_ylabel("(f(w_k) - f*) / (f(w_0) - f*)")
    ax.set_title("Same algorithm, same optimal step: scaling changes everything")
    ax.legend()
    save(fig, "3_scaling")
    macro("kappaRaw", sci(L_r / mu_r))
    md.append("")


# --------------------------------------------------- 4. numerical stability study
def experiment_stability():
    x = np.linspace(0, 1, 100)
    degrees = list(range(1, 15))
    conds, err_ne, err_qr, err_np = [], [], [], []
    for d in degrees:
        V = np.vander(x, d + 1, increasing=True)
        w_true = np.ones(d + 1)
        yy = V @ w_true
        conds.append(np.linalg.cond(V))
        try:
            err_ne.append(np.linalg.norm(ls.fit_normal_equations(V, yy) - w_true) / np.linalg.norm(w_true))
        except np.linalg.LinAlgError:
            err_ne.append(np.nan)
        err_qr.append(np.linalg.norm(ls.fit_qr(V, yy) - w_true) / np.linalg.norm(w_true))
    conds = np.array(conds)
    eps = np.finfo(float).eps
    fig, ax = plt.subplots(figsize=(7, 4.2))
    ax.loglog(conds, np.maximum(err_ne, 1e-17), "o-", color=GREY, label="normal equations (Cholesky)")
    ax.loglog(conds, np.maximum(err_qr, 1e-17), "o-", color=ORANGE, label="QR (Householder)")
    ax.loglog(conds, eps * conds, "--", color=ORANGE, lw=1, alpha=0.7, label="eps x cond(X)")
    ax.loglog(conds, np.minimum(eps * conds ** 2, 1e3), "--", color=GREY, lw=1, alpha=0.7, label="eps x cond(X)^2")
    ax.set_ylim(1e-17, 1e3)
    ax.set_xlabel("cond(X)")
    ax.set_ylabel("relative error on w")
    ax.set_title("Polynomial fit (Vandermonde matrix): accuracy of each method")
    ax.legend(fontsize=8)
    save(fig, "4_stability")
    md.extend(["## 4. Numerical stability: polynomial regression (Vandermonde matrix, exact data)", "",
               "| Degree | cond(X) | Error, normal equations | Error, QR |", "|---|---|---|---|"])
    rows_tex = []
    for d in (4, 8, 10, 12, 14):
        i = degrees.index(d)
        ne = "failed (not positive definite)" if np.isnan(err_ne[i]) else f"{err_ne[i]:.1e}"
        md.append(f"| {d} | {conds[i]:.1e} | {ne} | {err_qr[i]:.1e} |")
        ne_tex = "\\'echec (non d\\'efinie positive)" if np.isnan(err_ne[i]) else f"${sci(err_ne[i])}$"
        rows_tex.append(f"{d} & ${sci(conds[i])}$ & {ne_tex} & ${sci(err_qr[i])}$ \\\\")
    tex.append("\\newcommand{\\tableStability}{%")
    tex.extend(rows_tex)
    tex.append("}")
    md.append("")


